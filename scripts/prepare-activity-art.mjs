import { mkdir, readFile, writeFile, access } from "node:fs/promises";
import { createHash } from "node:crypto";
import sharp from "sharp";

const pack = new URL("../doita-test/doita-activity-art/", import.meta.url);
const target = new URL("../public/themes/sunset/activities/", import.meta.url);
const activities = JSON.parse(
  await readFile(new URL("activities.json", pack), "utf8"),
);
const seed = JSON.parse(
  await readFile(new URL("../data/activities.json", import.meta.url), "utf8"),
);
const registry = {};
const outputs = [];

// Validate the whole mapping before writing; preserve every supplied source.
for (const item of activities) {
  if (
    !/^(chat|play|watch|romantic|future)-\d{2}$/.test(item.id) ||
    registry[item.id]
  )
    throw new Error(`Invalid or duplicate activity ID: ${item.id}`);
  const row = seed.find((candidate) => candidate.id === item.id);
  if (!row || row.title !== item.title || row.description !== item.description)
    throw new Error(`Activity text differs from mapping: ${item.id}`);
  if (item.image !== `/assets/activities/${item.id}.webp`)
    throw new Error(`Unexpected image mapping: ${item.id}`);
  let data;
  const web = new URL(`public/assets/activities/${item.id}.webp`, pack);
  try {
    await access(web);
    data = await readFile(web);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    const png = new URL(`missing/${item.id}.png`, pack);
    data = await sharp(await readFile(png))
      .resize(512, 512, {
        fit: "contain",
        background: { r: 0, g: 0, b: 0, alpha: 0 },
      })
      .webp({ quality: 92, alphaQuality: 100 })
      .toBuffer();
  }
  const metadata = await sharp(data).metadata();
  if (
    metadata.format !== "webp" ||
    metadata.width !== 512 ||
    metadata.height !== 512 ||
    !metadata.hasAlpha
  )
    throw new Error(`Unexpected artwork format: ${item.id}`);
  const version = createHash("sha256").update(data).digest("hex").slice(0, 10);
  registry[item.id] = `/themes/sunset/activities/${item.id}.webp?v=${version}`;
  outputs.push({ id: item.id, data });
}
if (activities.length !== seed.length)
  throw new Error("Incomplete activity mapping");
await mkdir(target, { recursive: true });
for (const { id, data } of outputs)
  await writeFile(new URL(`${id}.webp`, target), data);
await writeFile(
  new URL("../src/config/activity-art.ts", import.meta.url),
  `// Generated by scripts/prepare-activity-art.mjs from the supplied activity mapping.\nexport const ACTIVITY_ART: Record<string, string> = ${JSON.stringify(registry, null, 2)};\n`,
);
console.log(
  `Prepared ${outputs.length} activity images; ${outputs.reduce((sum, item) => sum + item.data.length, 0)} bytes; sources unchanged.`,
);
